package ir.vil3ntec.tohid.core.sync

/**
 *  صفِ opهای Sync v1 که هنوز به سرور نرسیده‌اند — **هیچ‌وقت چیزی از آن دور ریخته نمی‌شود**.
 *
 *  پیش‌تر صف (اندروید/کامپیوتر `OpQueue`، وب `OpQueue` ِ `license/sync-core.js`) از ۵۰٬۰۰۰ op بالاتر
 *  که می‌رفت **کهنه‌ترین‌ها را کنار می‌گذاشت** (`queue_overflow`) و آن تغییرها هرگز به سرور نمی‌رسیدند —
 *  دکانی که چند هفته آفلاین کار کرده بود فروش‌های نخستینش را بی‌صدا گم می‌کرد. تصمیمِ سرپرست:
 *    • تغییرِ کاربر هرگز کنار گذاشته نمی‌شود؛ روی دستگاه می‌ماند و دسته‌دسته فرستاده می‌شود.
 *    • صفِ بزرگ ([WARN_AT] به بالا) با پیامِ روشن [warning] دیده می‌شود («X تغییر هنوز به سرور نرسیده»)،
 *      در همان جای پیامِ نوارِ همگام‌سازی، بی قرمز کردنِ چراغ.
 *    • حافظهٔ واقعاً پر ⇒ نوشتنِ تازه با پیامِ روشن رد می‌شود (دفترِ دیسک‌نشده op نمی‌سازد: F0-01؛
 *      وب: «حافظهٔ مرورگر پر است»)، نه انداختنِ کهنه‌ها.
 *
 *  قرینهٔ `QUEUE_WARN` / `backlogWarning` در `license/sync-core.js`؛ هر دو با
 *  `core/test-vectors/op-backlog-v1.json` سنجیده می‌شوند. Kotlinِ خالص (commonMain)، بی java.*.
 */
object OpBacklog {
  /** از این شمار به بالا پیامِ «هنوز نرسیده» دیده می‌شود (حدودِ چهار روز کارِ آفلاینِ دکانِ شلوغ) */
  const val WARN_AT: Int = 10_000

  /** پیامِ صفِ بزرگ؛ زیرِ [WARN_AT] رشتهٔ خالی */
  fun warning(queued: Int): String =
    if (queued < WARN_AT) "" else "${faCount(queued)} تغییر هنوز به سرور نرسیده؛ روی همین دستگاه نگه داشته شده‌اند — به اینترنت وصل بمانید تا برسند"

  /** عدد با رقمِ فارسی و جداکنندهٔ هزارگانِ «٬» — همان شکلِ نوارِ همگام‌سازی */
  fun faCount(n: Int): String {
    val digits = (if (n < 0) 0 else n).toString()
    val out = StringBuilder()
    for (i in digits.indices) {
      if (i > 0 && (digits.length - i) % 3 == 0) out.append('٬')
      out.append('۰' + (digits[i] - '0'))
    }
    return out.toString()
  }
}
