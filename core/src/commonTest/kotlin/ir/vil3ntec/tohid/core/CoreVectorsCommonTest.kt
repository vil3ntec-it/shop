  private fun hex(b: ByteArray) = b.joinToString("") { (it.toInt() and 0xFF).toString(16).padStart(2, '0') }

  @Test fun platform() {
    assertEquals("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", hex(sha256("abc".encodeToByteArray())))
    assertEquals("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", hex(sha256(ByteArray(0))))
    assertEquals(16, secureRandomBytes(16).size)
    assertEquals(0, secureRandomBytes(0).size)
    assertNotEquals(hex(secureRandomBytes(16)), hex(secureRandomBytes(16)))
  }

  /** همان `Math.round` ِ JVM، حتی در لبه‌هایی که `floor(x + 0.5)` خطا می‌کند */
  @Test fun mathRoundEdges() {
    assertEquals(0L, mathRound(0.49999999999999994), "0.49999999999999994")
    assertEquals(0L, mathRound(-0.49999999999999994), "-0.49999999999999994")
    assertEquals(1L, mathRound(0.5), "0.5")
    assertEquals(0L, mathRound(-0.5), "-0.5")
    assertEquals(2L, mathRound(1.5), "1.5")
    assertEquals(-1L, mathRound(-1.5), "-1.5")
    assertEquals(3L, mathRound(2.5), "2.5")
    assertEquals(-2L, mathRound(-2.5), "-2.5")
    assertEquals(4503599627370497L, mathRound(4503599627370497.0), "4503599627370497.0")
    assertEquals(-4503599627370497L, mathRound(-4503599627370497.0), "-4503599627370497.0")
    assertEquals(9007199254740992L, mathRound(9007199254740992.0), "9007199254740992.0")
    assertEquals(9223372036854775807L, mathRound(1e+300), "1e+300")
    assertEquals(Long.MIN_VALUE, mathRound(-1e+300))
    assertEquals(0L, mathRound(0.0), "0.0")
    assertEquals(0L, mathRound(-0.0), "-0.0")
    assertEquals(0L, mathRound(5e-324), "5e-324")
    assertEquals(Long.MAX_VALUE, mathRound(Double.POSITIVE_INFINITY))
    assertEquals(Long.MIN_VALUE, mathRound(Double.NEGATIVE_INFINITY))
    assertEquals(0L, mathRound(Double.NaN))
  }

  @Test fun ulid() {
    val b32 = Regex("^[0-9A-HJKMNP-TV-Z]{26}$")
    val a = Ulid.next(1760000000000L)
    val b = Ulid.next(1760000000000L)
    assertTrue(b32.matches(a), a)
    assertEquals("01K742SG00", a.take(10))
    assertTrue(b > a, "$a < $b")
    assertTrue(b32.matches(Ulid.next()))
  }

