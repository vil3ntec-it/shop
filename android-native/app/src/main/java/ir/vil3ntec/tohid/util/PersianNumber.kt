/**
 *  رقمِ فارسی.
 *
 *  ── چرا یک فایلِ جدا ───────────────────────────────────────────────
 *  متنِ برنامه فارسی است ولی عددها لاتین بودند: «۱۲ قرض‌دار» می‌شد
 *  «12 قرض‌دار». روی یک صفحه‌ی پر از متنِ فارسی، عددِ لاتین مثلِ چیزی
 *  از یک برنامه‌ی دیگر دیده می‌شود.
 *
 *  همه‌ی نمایشِ عددها از `Format.kt` می‌گذرد و آن هم از همین‌جا؛ پس
 *  شکلِ رقم یک جا تعریف شده است. آنچه کاربر **می‌نویسد** از این راه
 *  نمی‌گذرد و `latinDigits()` هم سرِ جایش است، پس خواندنِ ورودی و
 *  خروجیِ CSV دست‌نخورده می‌ماند.
 *  ──────────────────────────────────────────────────────────────────
 */
private val DIGITS = charArrayOf('۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹')

/** رقم‌های لاتینِ یک رشته را فارسی می‌کند؛ بقیه‌ی نویسه‌ها دست‌نخورده */
fun String.faDigits(): String {
  if (none { it in '0'..'9' }) return this
  val out = StringBuilder(length)
  for (c in this) out.append(if (c in '0'..'9') DIGITS[c - '0'] else c)
  return out.toString()
}

