package ir.vil3ntec.tohid.data

/**
 *  پیش‌فرضِ «ترکیبی و شیفت» (`ShopPolicy.payV2`) برای دستگاهی که هرگز انتخاب نکرده — خواستِ صاحب‌کار ۱۴۰۵/۰۸/۲۵ («جای پرداخت
 *  چرا حساب‌های کاربری نمیاد … این‌ها همه باید بیایند یا نقدی»، `claude/e-paymethods`): مثلِ صندوق‌های حرفه‌ای، تسویه همهٔ
 *  روش‌های پرداختِ دکان را نشان می‌دهد (نقد، کارت، حساب‌پی، کیف پول، حواله، نسیه)، نه فقط «نقدی | نسیه».
 *
 *  ⛔ انتخابِ صریح (هر کدام، کلیدِ `pay_v2` هست) دست نمی‌خورد ([Step.KEEP]).
 *  ⛔ صندوقِ باز گم یا خراب نمی‌شود: هر دو حالت همان ردیفِ `shift_open` را می‌خوانند، ولی «موردِ انتظار» ِ صندوقِ ساده
 *     (`CashShift.totals`) و صندوقِ شیفت (`PayFlow.report`، هستهٔ pay-core) در لبه‌ها (رویدادی که هسته نمی‌پذیرد، مثلاً خروجِ
 *     بیش از نقدِ دخل) یکی نیستند. پس جابه‌جایی فقط وقتی است که **هیچ** صندوقی باز نیست، یا هر صندوقِ باز در هر دو حالت
 *     بی هیچ رویدادِ کنارگذاشته و با **همان** نقدِ موردِ انتظار (تا پول) خوانده می‌شود — یعنی پس از جابه‌جایی همان عدد و همان
 *     ردیف‌ها، و بستنش با Z همان را می‌گوید. وگرنه [Step.WAIT]: تا آن صندوق بسته شود همان صندوقِ ساده (شروعِ بعدیِ برنامه
 *     دوباره می‌سنجد). جابه‌جایی هیچ ردیفی در دفتر نمی‌نویسد و هیچ ردیفی را عوض نمی‌کند.
 *
 *  قدم فقط در شروعِ برنامه (`ShopStore.loadAndSummarize`، پس از خواندنِ سالمِ دفتر؛ دفترِ خوانده‌نشده هرگز «بی صندوق» شمرده
 *  نمی‌شود) — نه درونِ صفحه‌ها، تا هیچ صفحه‌ای در میانِ کار حالتش عوض نشود. راهِ برگشت همان تنظیمِ «نقد و نسیه | ترکیبی و شیفت».
 */
object PayV2Default {

  enum class Step {
    /** کاربر خودش انتخاب کرده (یا پیش‌تر پذیرفته شد) ⇒ دست نمی‌خورد */
    KEEP,
    /** هرگز انتخاب نکرده و جابه‌جایی بی‌خطر است ⇒ «ترکیبی و شیفت» */
    ADOPT,
    /** هرگز انتخاب نکرده ولی صندوقِ بازی هست که در صندوقِ شیفت عددِ دیگری می‌گیرد ⇒ تا بسته شدنش همان صندوقِ ساده */
    WAIT,
  }

  /** @param chosen کلیدِ `pay_v2` روی همین دستگاه هست (انتخابِ صریح یا پذیرشِ پیشین) */
  fun step(chosen: Boolean, d: ShopData, now: Long): Step = when {
    chosen -> Step.KEEP
    CashShift.list(d).filter { it.isOpen }.all { sameUnderV2(d, it, now) } -> Step.ADOPT
    else -> Step.WAIT
  }

  /**
   *  صندوقِ بازِ [s] در صندوقِ شیفت همان است که در صندوقِ ساده: هسته همهٔ رویدادها را می‌پذیرد (هیچ `skipped`) و نقدِ موردِ
   *  انتظار تا پول برابر است. هر خطای گزارش ⇒ نه (احتیاط).
   */
  fun sameUnderV2(d: ShopData, s: CashShift.Shift, now: Long): Boolean {
    if (!s.isOpen) return true
    val legacy = CashShift.totalsOf(d, s, now).expected
    if (legacy.isNaN() || legacy.isInfinite()) return false
    val r = PayFlow.report(d, s.open, null, now).valueOrNull() ?: return false
    if (r.skipped.isNotEmpty()) return false
    val cash = r.report.expected?.get(PayFlow.CASH) ?: return false
    return cash == PayFlow.minor(legacy)
  }
}
