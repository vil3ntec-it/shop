package ir.vil3ntec.tohid.data

/**
 *  پیدا کردنِ کالا از بارکد — حتی از نیمهٔ بارکد.
 *
 *  ── چرا نیمه ───────────────────────────────────────────────────────
 *  خواسته‌ای که رسید، از سرِ کارِ واقعیِ دکان است: نورِ لامپ می‌افتد سرِ
 *  بارکد و نصفش سفید می‌شود. آن نصفِ دیگر خوانده می‌شود ولی به تنهایی
 *  «کدِ کالا» نیست، پس برنامه می‌گفت «بارکد ناشناس» — در حالی که همان
 *  چند رقم برای شناختنِ کالا کافی بود.
 *
 *  همین راه، دستِ فروشنده را هم باز می‌کند: هر چند رقمی را که روی
 *  بسته می‌بیند در کادرِ دستی می‌زند و کالا پیدا می‌شود؛ لازم نیست
 *  سیزده رقم را از زیرِ نورِ لامپ در بیاورد.
 *  ──────────────────────────────────────────────────────────────────
 *
 *  ── قاعده‌ای که از اشتباه جلو می‌گیرد ──────────────────────────────
 *  نیمه‌شناسی فقط وقتی جواب می‌دهد که **یکتا** باشد. اگر آن چند رقم به
 *  دو کالا بخورد، هیچ‌کدام انتخاب نمی‌شود و به کاربر گفته می‌شود چند تا
 *  هستند — چون در دکان، افزودنِ کالای غلط به سبد بدتر از نخواندنِ
 *  بارکد است: پولِ اشتباه از مشتری گرفته می‌شود و موجودیِ اشتباه کم
 *  می‌شود.
 *
 *  و کمتر از شش رقم اصلاً نیمه به حساب نمی‌آید؛ سه‌چهار رقم در دکانی با
 *  صد قلم جنس، تصادفی هم می‌خورد.
 */
object BarcodeMatch {

  /** کوتاه‌تر از این، نیمه به حساب نمی‌آید */
  const val MIN_PART = 6

  sealed interface Hit {
    /** @param exact درست است اگر کاملِ بارکد خوانده باشد، نه نیمه‌اش */
    data class Product(val id: String, val exact: Boolean) : Hit
    /** چند کالا با این نیمه می‌خوانند — انتخاب کارِ آدم است، نه برنامه */
    data class Several(val count: Int) : Hit
    data object None : Hit
  }

  /**
   *  @param index همان `ShopStore.barcodeIndex` — بارکد به شناسهٔ کالا
   */
  fun find(code: String, index: Map<String, String>): Hit {
    val clean = code.trim()
    if (clean.isEmpty()) return Hit.None

    //  اولْ کاملْ — تندترین و مطمئن‌ترین راه، و همان راهِ همیشگی
    index[clean]?.let { return Hit.Product(it, true) }

    if (clean.length < MIN_PART) return Hit.None

    /*
     *  دو طرفه سنجیده می‌شود:
     *   • بارکدِ ثبت‌شده این نیمه را **در خود دارد** → نیمهٔ خوانده‌شده
     *   • خوانده‌شده بارکدِ ثبت‌شده را در خود دارد → خوانشی که چیزِ
     *     اضافه چسبانده (ITFِ نصفه‌خوانده این‌طور می‌شود)
     */
    val ids = index.entries
      .filter { (known, _) ->
        known.length >= MIN_PART && (known.contains(clean) || clean.contains(known))
      }
      .map { it.value }
      .distinct()

    return when (ids.size) {
      0 -> Hit.None
      1 -> Hit.Product(ids.first(), false)
      else -> Hit.Several(ids.size)
    }
  }
}
