package ir.vil3ntec.tohid.sync

import ir.vil3ntec.tohid.BuildConfig

/**
 *  نشانیِ سرور — یک جا، نه پخش در صفحه‌ها.
 *
 *  تا امروز کاربر خودش نشانی را در تنظیمات می‌زد. یعنی هر کسی که برنامه
 *  را باز می‌کرد نشانیِ سرور را می‌دید، و هر کسی می‌توانست برنامه را به
 *  سرورِ خودش وصل کند. حالا نشانی در زمانِ ساخت داخلِ برنامه می‌نشیند و
 *  رابط کاربری‌اش برداشته شده.
 *
 *  چیزی که اینجا می‌نشیند باید **دامنهٔ عمومی** باشد، نه IP و پورتِ
 *  واقعیِ سرور: هر رشته‌ای که در فایلِ برنامه باشد خوانده می‌شود، پس
 *  سرورِ خانگی باید پشتِ یک دامنه و HTTPS بنشیند.
 */
object ApiBase {

  /** نشانیِ ساخت — اگر خالی باشد یعنی این نسخه به سروری بسته نشده */
  val fixed: String = BuildConfig.API_BASE.trim().trimEnd('/')

  /** آیا نشانی در خودِ برنامه نشسته است */
  val locked: Boolean get() = fixed.isNotBlank()
}
