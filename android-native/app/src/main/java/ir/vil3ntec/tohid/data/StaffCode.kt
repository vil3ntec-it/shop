package ir.vil3ntec.tohid.data

/**
 *  کدِ شاگرد — همان چیزی که صاحب دکان به کارمندش می‌دهد.
 *
 *  ── چه چیزی اینجا درست شد ──────────────────────────────────────────
 *  تا دیروز برنامه **خودش** یک کدِ شاگرد می‌ساخت: یک رشتهٔ تصادفی که
 *  در حافظهٔ همان گوشی می‌نشست و سرور هیچ خبری از آن نداشت. صاحب دکان
 *  همان را از تنظیمات کپی می‌کرد و به شاگردش می‌داد، شاگرد می‌زد، و
 *  سرور می‌گفت «این کد معتبر نیست» — چون واقعاً هم نبود. کدِ درست فقط
 *  روی سرور ساخته می‌شود و برنامه باید همان را نشان بدهد، نه ساختهٔ
 *  خودش را.
 *  ──────────────────────────────────────────────────────────────────
 *
 *  اینجا فقط سنجشِ **قالب** مانده، برای اینکه غلطِ تایپی پیش از رفتن به
 *  سرور گرفته شود. خودِ درستی و اعتبار و مهلتِ کد، کارِ سرور است و
 *  همان‌جا هم سنجیده می‌شود.
 *
 *  چرا دسته‌های ۴ یا ۵ نویسه‌ای: سرور کدِ ۴-۴-۴ می‌سازد و نسخهٔ وب
 *  ۵-۵-۵. سخت‌گیریِ بیشتر از این یعنی برنامه کدِ **درستِ** سرور را هم
 *  پیش از فرستادن رد کند — دقیقاً همان اشکالی که بود.
 */
object StaffCode {

  private val PATTERN = Regex("^SHG-[A-Z0-9]{4,5}(-[A-Z0-9]{4,5}){2}$")

  /** نمونه‌ای که در کادرِ ورودی به‌عنوان راهنما نوشته می‌شود */
  const val HINT = "SHG-XXXX-XXXX-XXXX"

  /**
   *  تمیز کردنِ آنچه کاربر زده.
   *
   *  کدی که با واتساپ می‌آید معمولاً فاصله یا فاصلهٔ نشکن هم دارد، و
   *  کاربر گاهی با حروفِ کوچک می‌نویسد. هیچ‌کدام دلیلِ رد کردن نیست.
   */
  fun clean(raw: String): String =
    raw.trim().uppercase().replace(" ", "").replace("‌", "").replace("_", "-")

  fun looksValid(raw: String): Boolean = PATTERN.matches(clean(raw))
}
