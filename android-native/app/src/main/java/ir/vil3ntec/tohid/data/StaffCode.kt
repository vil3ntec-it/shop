package ir.vil3ntec.tohid.data

/**
 *  کدِ پیوستن — همان چیزی که صاحب دکان به شاگردش می‌دهد.
 *
 *  ── چه چیزی اینجا درست شد ──────────────────────────────────────────
 *  تا دیروز برنامه **قالبِ** کد را هم خودش می‌سنجید: باید `SHG-` داشت و
 *  سه دستهٔ چهار-پنج نویسه‌ای. کدی که سرورِ صاحب مخزن می‌سازد این شکل
 *  نیست (`F6D75A07`)، پس برنامه کدِ **درست و زنده** را پیش از رسیدن به
 *  سرور رد می‌کرد و می‌گفت «این کد درست نیست» — در حالی که همان کد در
 *  پنل، فعال و آمادهٔ استفاده بود.
 *
 *  درسش روشن است: قالبِ کد را سرور تعیین می‌کند، نه گوشی. سرورها هم
 *  یکسان نیستند و با هر به‌روزرسانی ممکن است عوض شود. اگر برنامه قالب
 *  را حدس بزند، هر بار که سرور چیزِ تازه‌ای بسازد، گوشی جلویش را
 *  می‌گیرد.
 *
 *  پس حالا اینجا فقط **تمیز کردن** است: فاصله و حروفِ کوچک و نویسه‌های
 *  نامرئیِ کپی‌شده از واتساپ. درستی و اعتبار و مهلت، همه کارِ سرور است
 *  و پیامش هم از همان‌جا می‌آید.
 *  ──────────────────────────────────────────────────────────────────
 */
object StaffCode {

  /** نمونه‌ای که در کادرِ ورودی به‌عنوان راهنما نوشته می‌شود */
  const val HINT = "کدی که صاحب دکان داده"

  /**
   *  تمیز کردنِ آنچه کاربر زده.
   *
   *  کدی که با واتساپ یا تلگرام می‌آید معمولاً فاصله، فاصلهٔ نشکن یا
   *  نویسهٔ جهت‌دهیِ راست‌به‌چپ هم دارد؛ کاربر هم گاهی با حروفِ کوچک
   *  می‌نویسد. هیچ‌کدام دلیلِ رد کردن نیست — فقط برداشته می‌شوند.
   *
   *  رقم‌های فارسی و عربی هم به لاتین برمی‌گردند: کسی که با صفحه‌کلیدِ
   *  فارسی «۷» می‌زند، همان ۷ را می‌خواهد.
   */
  fun clean(raw: String): String {
    val sb = StringBuilder()
    for (ch in raw.trim()) {
      val c = when (ch) {
        in '۰'..'۹' -> '0' + (ch - '۰')
        in '٠'..'٩' -> '0' + (ch - '٠')
        '_' -> '-'
        else -> ch
      }
      //  فاصله و نویسه‌های نامرئی بیرون می‌روند، بقیه می‌مانند
      if (c.isWhitespace() || c.code == 0x200C || c.code == 0x200F || c.code == 0x200E) continue
      sb.append(c)
    }
    return sb.toString().uppercase()
  }

  /**
   *  آیا اصلاً چیزی برای فرستادن هست.
   *
   *  تنها سنجشِ باقی‌مانده — و عمداً همین‌قدر ساده: خالی نباشد و آن‌قدر
   *  بلند نباشد که معلوم باشد کاربر یک متنِ کامل را چسبانده.
   */
  fun usable(raw: String): Boolean = clean(raw).length in 4..40
}
