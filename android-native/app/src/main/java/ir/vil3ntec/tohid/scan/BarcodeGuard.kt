package ir.vil3ntec.tohid.scan

/**
 *  سدِ بارکدِ دروغین.
 *
 *  ── چه اشکالی را می‌گیرد ────────────────────────────────────────────
 *  گزارشِ کاربر دو چیز بود و هر دو یک ریشه دارند:
 *    • «گاهی یک کدِ رندم می‌آورد»
 *    • «نصفِ کد درست است و نصفِ دیگرش خراب»
 *
 *  عکسی هم که فرستاد گویا بود: `49495030626` — **یازده رقم**. هیچ
 *  بارکدِ استانداردی یازده رقم نیست. این خوانشِ **نصفه** است، نه یک کد.
 *
 *  چرا پیش می‌آید: از هفت قالبی که می‌خوانیم، `ITF` بدترینشان است.
 *  ITF رقم‌ها را **دوتادوتا** رمز می‌کند و جز یک الگوی آغاز و پایان،
 *  هیچ نگهبانی ندارد. اگر دوربین نیمی از بارکد را تار ببیند یا لبهٔ
 *  کادر آن را ببرد، همان نیمه می‌تواند مثلِ یک کدِ کاملِ کوتاه‌تر
 *  رمزگشایی شود — و بی هیچ نشانه‌ای تحویل داده شود. `CODE_39` و
 *  `CODE_128` هم رقمِ کنترلیِ اجباری ندارند.
 *
 *  خانوادهٔ EAN و UPC ولی رقمِ کنترلی دارند و همین‌جا سنجیده می‌شود.
 *  ──────────────────────────────────────────────────────────────────
 *
 *  ── سه سدِ پشتِ سرِ هم ──────────────────────────────────────────────
 *
 *  **۱. ساختار.** پیش از هر شمارشی، خوانشی که *نمی‌تواند* یک کدِ درست
 *  باشد همان‌جا دور ریخته می‌شود و اصلاً به حساب نمی‌آید:
 *    • ITF با طولِ **فرد** — ITF دوتادوتا رمز می‌کند، پس طولِ فرد یعنی
 *      خوانش نصفه مانده. همان `49495030626` اینجا می‌افتد.
 *    • EAN/UPC با رقمِ کنترلیِ غلط.
 *    • هر کدِ خیلی کوتاه.
 *
 *  **۲. رقمِ کنترلی.** کدی که طولش ۸ یا ۱۲ یا ۱۳ یا ۱۴ رقم است
 *  (GTIN-8، UPC-A، EAN-13، ITF-14) رقمِ کنترلی دارد. اگر بخواند، ریاضی
 *  تأییدش کرده و کار تمام است.
 *
 *  **۳. تکرار — و اینجا تازگیِ کار است.** چند بارِ یکسان لازم است، به
 *  دو چیز بستگی دارد: رقمِ کنترلی، و اینکه **این کد در فهرستِ کالاهای
 *  دکان هست یا نه**.
 *
 *      | | در فهرست هست | ناشناس |
 *      |---|---|---|
 *      | رقمِ کنترلی درست | ۱ بار | ۲ بار |
 *      | ITF بدونِ رقمِ کنترلی | ۳ بار | **۵ بار** |
 *      | بقیه | ۲ بار | ۴ بار |
 *
 *  منطقش ساده است: کالای واقعیِ دکان باید **همان فریمِ اول** برود توی
 *  سبد — فروشنده نباید منتظر بماند. ولی کدی که در فهرست نیست، هر چه
 *  باشد کارِ فوری‌ای با آن نیست (فقط پیغامِ «بارکد ناشناس» می‌دهد)، پس
 *  می‌شود بیشتر از آن مدرک خواست. و خوانشِ نصفه تقریباً همیشه ناشناس
 *  است، چون نصفهٔ یک کد در فهرست نیست. یعنی سخت‌گیری دقیقاً همان‌جا
 *  می‌افتد که اشتباه می‌افتد و هیچ کالای درستی را کند نمی‌کند.
 *
 *  روی سی فریم در ثانیه، پنج بار یعنی حدودِ یک‌ششمِ ثانیه — آدم
 *  نمی‌فهمد، ولی خوانشِ نصفه از آن رد نمی‌شود چون با هر تکانِ دست،
 *  جایِ بریدگی عوض می‌شود و عددِ دیگری در می‌آید.
 *  ──────────────────────────────────────────────────────────────────
 *
 *  ── چرا شمارش برای هر کد جداست ─────────────────────────────────────
 *  پیش‌تر فقط یک کد در دست بود و رسیدنِ کدِ دیگر شمارش را از صفر
 *  می‌کرد. در عمل، دوربینِ نیمه‌تار یکی‌درمیان کدِ درست و کدِ نصفه
 *  می‌دهد؛ آن‌طور کدِ درست هیچ‌وقت به حدِ نصاب نمی‌رسید و اسکن «گیر»
 *  می‌کرد. حالا هر کد شمارشِ خودش را دارد و هر کدام زودتر رسید،
 *  همان می‌برد.
 *  ──────────────────────────────────────────────────────────────────
 *
 *  چرا رقمِ کنترلیِ نخوان یکسره «رد» نمی‌شود و فقط تکرار می‌خواهد:
 *  دکان‌هایی هستند که کدِ داخلیِ خودشان را چاپ می‌کنند و رقمِ کنترلی‌اش
 *  درست نیست. رد کردنش یعنی کالایی که تا دیروز اسکن می‌شد، امروز نشود —
 *  و آن، درست کردنِ یک اشکال با ساختنِ اشکالِ بزرگ‌تر است.
 */
object Gtin {

  /** طول‌هایی که رقمِ کنترلی دارند: GTIN-8، GTIN-12، GTIN-13، GTIN-14 */
  private val LENGTHS = setOf(8, 12, 13, 14)

  /** آیا این کد قابلِ سنجش است — عددِ خالص با طولِ استاندارد */
  fun verifiable(code: String): Boolean =
    code.length in LENGTHS && code.all { it in '0'..'9' }

  /**
   *  سنجشِ رقمِ کنترلی — همان قاعدهٔ GTIN.
   *
   *  از راست به چپ، وزنِ ۳ و ۱ یکی‌درمیان. همین یک قاعده هر چهار طول را
   *  می‌پوشاند، پس لازم نیست برای EAN-13 و UPC-A و EAN-8 سه تابعِ جدا
   *  نوشته شود.
   */
  fun valid(code: String): Boolean {
    if (!verifiable(code)) return false
    var sum = 0
    code.dropLast(1).reversed().forEachIndexed { i, ch ->
      sum += (ch - '0') * if (i % 2 == 0) 3 else 1
    }
    return (10 - sum % 10) % 10 == code.last() - '0'
  }
}

/**
 *  خانوادهٔ بارکد — همان‌قدر که سد به آن نیاز دارد، نه بیشتر.
 *
 *  عمداً از `Barcode.FORMAT_*`ِ ML Kit جداست: سد را باید بشود روی JVM
 *  و بدونِ دوربین سنجید. ترجمه‌اش یک‌جا در `BarcodeScanner` است.
 */
enum class CodeKind {
  /** EAN-13، EAN-8، UPC-A — رقمِ کنترلیِ اجباری دارند */
  CHECKED,

  /** ITF — دوتادوتا رمز می‌شود و نیمه‌خوانی‌اش بی‌صداست */
  ITF,

  /** CODE-39، CODE-128، UPC-E، ورودیِ دستی، و هر چه دیگر */
  OTHER,
}

/**
 *  @param windowMs پنجرهٔ تکرار — بیش از این فاصله، شمارش از نو
 *  @param known آیا این کد در فهرستِ کالاهای دکان هست
 */
class BarcodeGuard(
  private val windowMs: Long = 1200,
  private val known: (String) -> Boolean = { false },
) {

  /** کوتاه‌تر از این، هیچ بارکدی نیست */
  private val minLength = 4

  /** کمترین طولِ ITF که به آن بها می‌دهیم — ITF-6 کمترینِ استاندارد است */
  private val minItf = 6

  private class Sighting(var count: Int, val firstAt: Long)

  /**
   *  شمارشِ هر کد جدا. بزرگ نمی‌شود: هر بار که تابع صدا زده می‌شود،
   *  هر چه از پنجره بیرون افتاده پاک می‌شود، و در یک پنجرهٔ یک‌ثانیه‌ای
   *  بیش از چند خوانشِ متفاوت نمی‌آید.
   */
  private val sightings = HashMap<String, Sighting>()

  /** آیا می‌شود به این خوانش اعتماد کرد */
  fun trust(
    code: String,
    kind: CodeKind = CodeKind.OTHER,
    now: Long = System.currentTimeMillis(),
  ): Boolean {
    //  سدِ اول: خوانشی که نمی‌تواند کدِ درستی باشد، اصلاً شمرده نمی‌شود
    if (!wellFormed(code, kind)) return false

    forget(now)

    val need = needed(code, kind)
    val seen = sightings.getOrPut(code) { Sighting(0, now) }
    seen.count++
    if (seen.count < need) return false
    reset()
    return true
  }

  /**
   *  آیا این خوانش اصلاً شکلِ یک بارکد را دارد.
   *
   *  اینجا «رد» یعنی رد؛ نه شمرده می‌شود و نه با تکرار می‌گذرد. چون
   *  اشکالش از جنسِ کم‌بودنِ مدرک نیست — از جنسِ ناممکن بودن است.
   */
  private fun wellFormed(code: String, kind: CodeKind): Boolean {
    if (code.length < minLength) return false
    return when (kind) {
      //  ML Kit خودش رقمِ کنترلیِ EAN و UPC را می‌سنجد؛ این یکی برای
      //  آن است که اگر روزی سنجش را از دست داد، ما از دست نداده باشیم
      CodeKind.CHECKED -> Gtin.valid(code)
      //  ریشهٔ همان «کدِ نصفه»: ITF دوتادوتا رمز می‌کند، پس طولِ فرد
      //  نشانهٔ قطعیِ خوانشِ ناتمام است
      CodeKind.ITF ->
        code.length >= minItf && code.length % 2 == 0 && code.all { it in '0'..'9' }
      CodeKind.OTHER -> true
    }
  }

  /** چند بارِ یکسان لازم است — جدولش بالا نوشته شده */
  private fun needed(code: String, kind: CodeKind): Int {
    val sure = Gtin.valid(code)
    val inShop = runCatching { known(code) }.getOrDefault(false)
    return when {
      sure && inShop -> 1
      sure -> 2
      inShop -> 2
      kind == CodeKind.ITF -> 5
      else -> 4
    }
  }

  /** هر چه از پنجره بیرون افتاده، دیگر مدرک نیست */
  private fun forget(now: Long) {
    if (sightings.isEmpty()) return
    val iterator = sightings.entries.iterator()
    while (iterator.hasNext()) {
      if (now - iterator.next().value.firstAt > windowMs) iterator.remove()
    }
  }

  fun reset() {
    sightings.clear()
  }
}
