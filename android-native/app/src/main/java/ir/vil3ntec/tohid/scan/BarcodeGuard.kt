package ir.vil3ntec.tohid.scan

/**
 *  سدِ بارکدِ دروغین.
 *
 *  ── چه اشکالی را می‌گیرد ────────────────────────────────────────────
 *  گزارش شد که «وقتی اسکن خراب است، کدهای رندم می‌آورد». این واقعاً
 *  ممکن است و علتش هم روشن است: از هفت قالبی که می‌خوانیم، `CODE_39` و
 *  `CODE_128` و `ITF`ِ کوتاه **رقمِ کنترلی اجباری ندارند**. یعنی اگر
 *  دوربین نصفِ یک بارکدِ تار را ببیند، ممکن است همان نصف را به‌عنوان یک
 *  کدِ کامل و «درست» تحویل بدهد. هیچ‌جای زنجیره هم نبود که بگوید «این
 *  عدد بی‌معنی است».
 *
 *  خانوادهٔ EAN و UPC ولی رقمِ کنترلی دارند و همین‌جا سنجیده می‌شود.
 *  ──────────────────────────────────────────────────────────────────
 *
 *  ── دو سدِ پشتِ سرِ هم ─────────────────────────────────────────────
 *   ۱. **رقمِ کنترلی.** کدی که طولش ۸ یا ۱۲ یا ۱۳ یا ۱۴ رقم است
 *      (GTIN-8، UPC-A، EAN-13، ITF-14) رقمِ کنترلی دارد. اگر بخواند،
 *      **همان فریمِ اول** پذیرفته می‌شود — بی هیچ تأخیری، چون ریاضی
 *      تأییدش کرده. این همان حالتِ نودوچند درصدِ کالای دکان است.
 *
 *   ۲. **تکرار.** هر کدِ دیگری — حروف‌دار، طولِ نامتعارف، یا رقمِ
 *      کنترلیِ نخوان — باید **سه بار** در پنجرهٔ کوتاهی یکسان خوانده
 *      شود. روی سی فریم در ثانیه این یعنی کمتر از یک‌دهمِ ثانیه؛ آدم
 *      نمی‌فهمد، ولی خوانشِ تصادفی از آن رد نمی‌شود چون دو بارِ پیاپی
 *      **همان** غلط را نمی‌دهد.
 *  ──────────────────────────────────────────────────────────────────
 *
 *  چرا رقمِ کنترلیِ نخوان «رد» نمی‌شود و فقط تکرار می‌خواهد: دکان‌هایی
 *  هستند که کدِ داخلیِ خودشان را چاپ می‌کنند و رقمِ کنترلی‌اش درست
 *  نیست. رد کردنش یعنی کالایی که تا دیروز اسکن می‌شد، امروز نشود —
 *  و آن، درست کردنِ یک اشکال با ساختنِ اشکالِ بزرگ‌تر است.
 */
object Gtin {

  /** طول‌هایی که رقمِ کنترلی دارند: GTIN-8، GTIN-12، GTIN-13، GTIN-14 */
  private val LENGTHS = setOf(8, 12, 13, 14)

  /** آیا این کد قابلِ سنجش است — عددِ خالص با طولِ استاندارد */
  fun verifiable(code: String): Boolean =
    code.length in LENGTHS && code.all { it in '0'..'9' }

  /**
   *  سنجشِ رقمِ کنترلی — همان قاعدهٔ GTIN.
   *
   *  از راست به چپ، وزنِ ۳ و ۱ یکی‌درمیان. همین یک قاعده هر چهار طول را
   *  می‌پوشاند، پس لازم نیست برای EAN-13 و UPC-A و EAN-8 سه تابعِ جدا
   *  نوشته شود.
   */
  fun valid(code: String): Boolean {
    if (!verifiable(code)) return false
    var sum = 0
    code.dropLast(1).reversed().forEachIndexed { i, ch ->
      sum += (ch - '0') * if (i % 2 == 0) 3 else 1
    }
    return (10 - sum % 10) % 10 == code.last() - '0'
  }
}

/**
 *  @param windowMs پنجرهٔ تکرار — بیش از این فاصله، شمارش از نو
 *  @param needed چند بارِ یکسان برای کدی که رقمِ کنترلی ندارد
 */
class BarcodeGuard(
  private val windowMs: Long = 900,
  private val needed: Int = 3,
) {

  private var pending: String? = null
  private var seen = 0
  private var firstAt = 0L

  /** آیا می‌شود به این خوانش اعتماد کرد */
  fun trust(code: String, now: Long = System.currentTimeMillis()): Boolean {
    if (Gtin.verifiable(code) && Gtin.valid(code)) {
      reset()
      return true
    }
    if (code != pending || now - firstAt > windowMs) {
      pending = code
      seen = 1
      firstAt = now
      return needed <= 1
    }
    seen++
    if (seen < needed) return false
    reset()
    return true
  }

  fun reset() {
    pending = null
    seen = 0
    firstAt = 0
  }
}
