'use strict';
/**
 * نسخهٔ برنامهٔ هر دستگاهِ دکان (مهاجرتِ ۹۸۰، `devices.app_version`) — فهرستِ «دستگاه‌ها» ِ صاحب (`GET /api/shop/devices`).
 *
 * برنامه روی هر درخواست `X-App-Version` می‌فرستد (گوشی `3.2.N`، کامپیوتر `1.0.N`، وب `3.2`، پیش‌نمایش `3.2.N-preview`).
 * `middleware/auth.js` همان جا که `last_seen_at` را می‌نویسد این را هم می‌نویسد؛ پس «تازه‌ترین نسخهٔ گزارش‌شده».
 *
 * ⛔ سرآیند دادهٔ بیرونی است: فقط شکلِ نسخه (رقم و نقطه، پسوندِ کوتاهِ `-preview`‌گونه)، حداکثر ۳۲ نویسه. هر چیزِ دیگر
 *    (متن، اسکریپت، رقمِ فارسی، بلند) ⇒ '' یعنی «ننوشتن» — مقدارِ پیشین می‌ماند و خودِ درخواست رد **نمی‌شود** (این سرآیند
 *    روی همهٔ درهاست؛ ساختِ کهنه یا ناجور نباید از کار بیفتد).
 */
const MAX = 32;
const SHAPE = /^\d{1,4}(\.\d{1,7}){1,3}(-[0-9A-Za-z.]{1,16})?$/;

/** مقدارِ درستِ نسخه یا '' (نبود، ناجور، بلند). «v» ِ آغاز برداشته می‌شود (همان `app-compat.valid`). */
function clean(raw) {
  if (typeof raw !== 'string') return '';
  const s = raw.trim().replace(/^v/i, '');
  return s.length <= MAX && SHAPE.test(s) ? s : '';
}

module.exports = { MAX, clean };
