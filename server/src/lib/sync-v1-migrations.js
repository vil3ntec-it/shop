'use strict';
/**
 * نسخهٔ Schema هر برنامه و Up-migrationهای سرور — Sync v1، بندِ ۲۰.۶.
 *
 * ── قاعده ─────────────────────────────────────────────────────────
 *   برنامهٔ قدیمی‌تر از سرور  ⇒ opهایش پذیرفته می‌شوند و همین‌جا به
 *                                schemaی تازه تبدیل می‌شوند؛ پاسخ
 *                                `upgrade_available: true` می‌گیرد.
 *   برنامهٔ جدیدتر از سرور    ⇒ `426 UPGRADE_REQUIRED`، هیچ opی اعمال
 *                                نمی‌شود، برنامه opها را نگه می‌دارد.
 *
 * هر جدول یا فیلدِ تازه = یک پله بالاتر این‌جا **و** یک migration در
 * خودِ برنامه با همان شماره. پله‌ای که این‌جا نباشد یعنی سرور آن schema
 * را نمی‌شناسد و opهایش را نمی‌پذیرد — این عمدی است.
 *
 * ── شکلِ هر پله ──────────────────────────────────────────────────
 *   MIGRATIONS[app][n] = (op) => op'
 *   یعنی «opی که با schema n−1 ساخته شده را به schema n ببر». تابع
 *   **خالص** است: یک op می‌گیرد و همان یا نسخهٔ تبدیل‌شده‌اش را
 *   برمی‌گرداند؛ نه دیتابیس می‌خواند نه چیزی می‌نویسد. پس همیشه به
 *   همان ترتیب و همان نتیجه می‌رسد، روی هر سروری.
 *
 * ⚠️ `hash`ِ op پیش از تبدیل سنجیده می‌شود (روی همان چیزی که برنامه
 * فرستاده) و بعد از تبدیل دیگر معتبر نیست؛ `apply` خودش خالی‌اش می‌کند.
 */

/** نسخهٔ فعلیِ schema هر بخش — همان که در `app_schema` نوشته می‌شود. */
const CURRENT = Object.freeze({
  //  پلهٔ ۲: فروش کانالِ خودش را دارد (فیزیکی / سفارشِ وب)
  //  پلهٔ ۳ (F0-04): سه جدولِ تازه — productCategories · productUnits ·
  //  expenseCategories. برنامهٔ پلهٔ ۲ همچنان پذیرفته می‌شود؛ برنامهٔ
  //  پلهٔ ۳ روی سرورِ پلهٔ ۲ ۴۲۶ می‌گیرد و opهایش را نگه می‌دارد (نه
  //  اینکه opهای این سه جدول «جدولِ ناشناخته» بگیرند و دور ریخته شوند).
  shop: 3,
  pump: 1,
});

/**
 * پله‌هایی که فقط با پرچمِ همان حساب روشن‌اند (`safe-flag.js`). پرچمِ خاموش ⇒ همان `CURRENT`،
 * یعنی سرور همان main است و برنامهٔ پلهٔ بالاتر با پلهٔ پایه می‌فرستد (`wireSchema` ِ برنامه‌ها).
 *   پلهٔ ۴ (PAY-18): جدولِ تازهٔ `safeEntries` (گاوصندوق)، پشتِ `sync.safe_entries`.
 */
const FLAGGED = Object.freeze({ shop: 4 });

const MIGRATIONS = {
  shop: {
    /**
     * ۱ → ۲: ردیفِ فروش فیلدِ `channel` گرفت.
     *
     * برنامهٔ نسخهٔ ۱ آن را نمی‌شناسد و نمی‌فرستد. فروشی که از آن‌جا
     * می‌آید فروشِ حضوریِ پشتِ دخل است، پس `insert`ِ بی‌کانال «pos»
     * می‌گیرد. `update` دست نمی‌خورد — فقط فیلدهای عوض‌شده را دارد و
     * پر کردنِ فیلدی که برنامه لمس نکرده، ویرایشِ کسِ دیگر را روی
     * همان فیلد می‌بلعید.
     */
    2: (op) => {
      if (op.table !== 'sales' || op.type !== 'insert') return op;
      if (op.fields && op.fields.channel !== undefined) return op;
      return { ...op, fields: { ...op.fields, channel: 'pos' } };
    },
    /**
     * ۲ → ۳: فقط جدولِ تازه آمد، هیچ فیلدِ موجودی عوض نشد — پس opِ
     * برنامهٔ پلهٔ ۲ همان‌طور می‌گذرد. پله نوشته شده تا معلوم باشد عمدی
     * است، نه فراموش‌شده.
     */
    3: (op) => op,
    /** ۳ → ۴: فقط جدولِ تازهٔ `safeEntries`؛ opِ برنامهٔ پلهٔ ۳ همان‌طور می‌گذرد. */
    4: (op) => op,
  },
  pump: {},
};

/**
 * نسخهٔ فعلیِ یک بخش؛ بخشِ ناشناخته ۰ (یعنی هیچ opی پذیرفته نمی‌شود).
 * @param ctx بافتِ همگام‌سازی (`req.sync`)؛ بی آن، `ctx` ِ درخواستِ Sync v1 ِ دکانِ همین لحظه
 *            (`safe-flag.within` — `sync-v1.js` ِ مشترک با پمپ ctx را نمی‌رساند). هیچ یا پرچمِ خاموش ⇒ `CURRENT`
 */
function currentVersion(app, ctx = null) {
  if (FLAGGED[app]) {
    const flag = require('./safe-flag');
    if (flag.on(flag.ctxOf(ctx))) return FLAGGED[app];
  }
  return CURRENT[app] || 0;
}

/**
 * یک op را از schemaی `from` تا نسخهٔ فعلی بالا می‌برد.
 *
 * پله‌ای که تابع ندارد یعنی «چیزی برای این جدول عوض نشده» و op همان‌طور
 * رد می‌شود؛ ولی پله‌ای که از `CURRENT` بزرگ‌تر باشد هرگز صدا زده
 * نمی‌شود — آن‌جا 426 است، نه این‌جا.
 */
function upgrade(app, from, op, ctx = null) {
  const to = currentVersion(app, ctx);
  let cur = op;
  for (let n = from + 1; n <= to; n++) {
    const step = MIGRATIONS[app] && MIGRATIONS[app][n];
    if (typeof step === 'function') cur = step(cur);
  }
  return cur;
}

module.exports = { CURRENT, FLAGGED, MIGRATIONS, currentVersion, upgrade };
