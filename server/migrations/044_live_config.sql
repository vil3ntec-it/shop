-- ============================================================
--  «تنظیماتِ زنده» ی برنامهٔ پمپ — بی آپدیتِ برنامه
--
--  خواستهٔ صاحب سامانه (۱۴۰۵/۰۷/۱۷): «برنامه رو جوری کن که بعدن اگه
--  قابلیتی خاستم بتونم راحت روش اجرا کنم… لایف اپدیت باشه… روی سرور فشاری
--  نیاد… هیچ منطقی رو دست نزن و خراب نکن.»
--
--  ⛔ فقط «مقدار» — هیچ کدی از این جدول اجرا نمی‌شود. برنامه فقط کلیدهایی را
--  می‌خواند که خودش می‌شناسد؛ کلیدِ ناشناخته دست‌نخورده می‌ماند.
--  scope = 'all' (همهٔ پمپ‌ها) یا شناسهٔ یک پمپ (بر 'all' جلو می‌افتد).
-- ============================================================

CREATE TABLE IF NOT EXISTS live_config (
  scope       text   NOT NULL,
  key         text   NOT NULL,
  --  JSONِ نوشته‌شده (رشته، عدد، درست/نادرست، فهرست یا شیء)
  value       text   NOT NULL,
  updated_at  bigint NOT NULL,
  updated_by  text   NOT NULL DEFAULT '',
  PRIMARY KEY (scope, key)
);

--  ⛔ شمارندهٔ هر scope فقط بالا می‌رود — پاک کردن هم آن را بالا می‌برد، پس
--  برنامه‌ای که نسخهٔ کهنه دارد همیشه می‌فهمد چیزی عوض شده.
CREATE TABLE IF NOT EXISTS live_config_versions (
  scope    text   PRIMARY KEY,
  version  bigint NOT NULL DEFAULT 0
);
