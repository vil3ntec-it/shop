-- ---------------------------------------------------------------------------
--  دستگاه‌های پمپ: چه کسی بندش کرد — تا با رفتنِ او، دستگاهش هم برود
--
--  ⛔ تا امروز توکنِ دستگاه (`pd_…`) هیچ پیوندی با حسابی که آن را ساخته
--  بود نداشت و تاریخِ انقضا هم ندارد. پس عضوی که از پمپ برداشته می‌شد
--  نشستِ حسابش باطل می‌شد، ولی کامپیوتری که با همان حساب بند کرده بود
--  تا ابد روی پوشه و چتِ مشتری‌های آن پمپ دست داشت.
-- ---------------------------------------------------------------------------
ALTER TABLE station_devices ADD COLUMN IF NOT EXISTS bound_by_user_id text;
CREATE INDEX IF NOT EXISTS idx_station_devices_bound_by
  ON station_devices (bound_by_user_id) WHERE bound_by_user_id IS NOT NULL;
