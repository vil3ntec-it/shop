-- ============================================================
--  پشتیبانِ هر حساب، جدا — روی ابر
-- ------------------------------------------------------------
--  ⛔ چیزی که تا امروز نبود و نبودنش گران بود:
--
--  `lib/backup.js` از **کلِ دیتابیس** `pg_dump` می‌گرفت. یعنی صاحبِ
--  سامانه یک فایل داشت و هیچ دکان‌دار یا پمپ‌داری پشتیبانِ خودش را
--  نه می‌توانست بفرستد، نه ببیند، نه برگرداند. و برگرداندنِ یک دکان
--  از آن فایل یعنی برگرداندنِ **همه‌ی** دکان‌ها به دیروز — که هیچ‌وقت
--  کسی جرئتش را ندارد، پس آن پشتیبان عملاً برای هیچ‌کس نبود.
--
--  برنامهٔ دکان پشتیبانش را فقط روی **خودِ گوشی** نگه می‌داشت
--  (`AutoBackup`): گوشی که گم یا آب شود، کارِ چند سال با آن می‌رود.
--  برنامهٔ پمپ به **سرورِ خانگی** می‌فرستاد: مودم که بسوزد، همان‌جا
--  می‌سوزد.
--
--  پس این جدول: هر دکان و هر پمپ، پوشه و سهمِ خودش.
--
--  ── چرا فایل روی دیسک است و ردیف در دیتابیس ─────────────────────
--  پشتیبانِ یک پمپِ پنج‌ساله چند صد مگابایت است. نگه داشتنش در
--  PostgreSQL یعنی هر `pg_dump`ِ خودمان هم همان چند صد مگابایت را با
--  خودش می‌برد و پشتیبانِ سامانه عملاً غیرقابلِ گرفتن می‌شد. پس فایل
--  روی دیسک می‌نشیند و این‌جا فقط نشانی و اندازه و مُهرش.
--
--  ── چرا `tenant_id` کلیدِ خارجی ندارد ────────────────────────────
--  چون به **دو** جدول اشاره می‌کند: `shops` و `stations`. همان قاعدهٔ
--  `vip_codes`/`station_vip_codes` نیست چون آن‌جا دو جدولِ جدا بود؛
--  این‌جا یک جدول با ستونِ `app` است، و `app` تنها چیزی است که
--  می‌گوید ردیف مالِ کدام دفتر است. هر پرس‌وجویی روی این جدول باید
--  **هم `app` و هم `tenant_id`** را شرط کند — بی آن، پمپی با همان
--  شناسه‌ی یک دکان پشتیبانِ او را می‌دید.
-- ============================================================

CREATE TABLE IF NOT EXISTS account_backups (
  id           text PRIMARY KEY,
  app          text NOT NULL,                     -- 'shop' | 'pump'
  tenant_id    text NOT NULL,                     -- shop_id یا station_id
  file         text NOT NULL,                     -- نامِ فایل در پوشهٔ همان حساب
  bytes        bigint NOT NULL,
  sha256       text NOT NULL DEFAULT '',
  label        text NOT NULL DEFAULT '',
  kind         text NOT NULL DEFAULT 'auto',      -- auto | manual
  app_version  text NOT NULL DEFAULT '',
  device_id    text NOT NULL DEFAULT '',
  user_id      text NOT NULL DEFAULT '',
  created_at   bigint NOT NULL
);

--  «پشتیبان‌های این حساب، تازه‌ترین اول» — تنها پرسشی که فهرست می‌زند
CREATE INDEX IF NOT EXISTS idx_account_backups_tenant
  ON account_backups(app, tenant_id, created_at DESC);

--  یک نام، یک بار. اگر دو درخواستِ هم‌زمان یک نام بسازند، دومی
--  همین‌جا می‌افتد نه این‌که فایلِ اولی را بی‌صدا بپوشاند.
CREATE UNIQUE INDEX IF NOT EXISTS idx_account_backups_file
  ON account_backups(app, tenant_id, file);
