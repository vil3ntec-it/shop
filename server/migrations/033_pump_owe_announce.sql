-- ============================================================
--  بدهیِ پمپ به شرکت‌ها + اعلامیهٔ روزانهٔ بات
--
--  خواستهٔ صاحب سامانه (۱۴۰۵/۰۷/۱۴): «یک اعلامیه بده که تیل بگیرید یا به
--  یارو تیل ندید یا از شرکت این‌قدر قرض‌دار استین… یکم ریس‌مدلی.»
--
--  ⛔ دفترِ دوم نیست: `owe` همان الباقیِ هر شرکت است که برنامهٔ کامپیوتر
--  حساب کرده و می‌فرستد؛ این‌جا هیچ عددی حساب نمی‌شود.
-- ============================================================
--  [{n, afn, usd}] — شرکت‌هایی که پمپ به آن‌ها بدهکار است
ALTER TABLE station_live_state ADD COLUMN IF NOT EXISTS owe jsonb;

--  روزی (به وقتِ کابل، YYYY-MM-DD) که اعلامیهٔ صبح به این گفت‌وگو رفت —
--  هر روز یک بار، نه با هر راه‌اندازیِ سرور
ALTER TABLE telegram_chats ADD COLUMN IF NOT EXISTS announced_day text;
