-- ══ پمپ: اشتراکِ دائمی با کدِ پلنِ «دائمی» (۱۴۰۵/۰۷/۲۰) ══════════════════════
--
-- «دائمی کن» تا ۲.۱۱.۲۳ فقط پلنِ خالی یا ‎custom‎ را ‎perm‎ می‌کرد؛ وی‌آی‌پی یا
-- استانداردی که دائمی شده بود همان نام را نگه می‌داشت و فقط پایانش پنجاه سال
-- جلو می‌رفت. از ۲.۱۱.۲۴ پلنِ زمان‌دارِ صریح (std/vip/trial) هرگز «دائمی»
-- خوانده نمی‌شود (‎lib/pump-services.js‎)، پس آن ردیف‌ها همین‌جا کدِ درست
-- می‌گیرند تا خدماتِ ساله‌شان همان بماند که بود. قابلیت‌ها دست نمی‌خورند.
UPDATE station_subscriptions
   SET plan = 'perm'
 WHERE plan IN ('std', 'vip')
   AND ends_at > (EXTRACT(EPOCH FROM now()) * 1000)::bigint + 10::bigint * 365 * 86400000;
