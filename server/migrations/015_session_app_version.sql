-- ============================================================
--  نسخه‌ی برنامه‌ای که هر نشست را ساخته
-- ------------------------------------------------------------
--  سرور از قبل می‌دانست هر نشست مالِ **کدام برنامه** است
--  (`tokens.app`)، ولی نمی‌دانست آن برنامه **کدام نسخه** است.
--
--  نبودنش دو جای مشخص درد داشت:
--
--    ۱) `min_app_version` در `/config` گفته می‌شود ولی هیچ‌وقت سنجیده
--       نمی‌شد که چند نفر هنوز زیرِ آن خط مانده‌اند.
--    ۲) وقتی گزارشی می‌رسد («فلان‌جا کار نمی‌کند»)، هیچ راهی نبود که
--       بشود فهمید آن گوشی چه نسخه‌ای دارد.
--
--  چرا روی `tokens` و نه `devices`: مسیرِ ورود با رمز اصلاً `device`
--  نمی‌فرستد، پس اگر روی `devices` می‌نشست، رایج‌ترین راهِ ورود هیچ
--  نسخه‌ای ثبت نمی‌کرد. هر نشست ولی یک ردیفِ توکن دارد — بی‌استثنا.
--
--  پیش‌فرضِ خالی یعنی «نگفت»: نسخه‌های امروزِ دستِ کاربر چیزی
--  نمی‌فرستند و نباید هم از کار بیفتند.
-- ============================================================

ALTER TABLE tokens ADD COLUMN IF NOT EXISTS app_version text NOT NULL DEFAULT '';

--  «چند نفر روی کدام نسخه‌اند» — پرسشی که این ستون برای آن اضافه شد
CREATE INDEX IF NOT EXISTS idx_tokens_app_version
  ON tokens(app, app_version)
  WHERE revoked_at IS NULL;
