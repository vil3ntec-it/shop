-- ============================================================
--  کدِ دسترسیِ هر پمپ — «هر کسی که برنامه را نصب می‌کند باید این کد را بزند»
--
--  ── خواستهٔ صاحب مخزن ────────────────────────────────────────
--  «برای هر حسابِ جیمیل یک کد باشد که توی برنامهٔ اندروید و آیفون
--   بزند، حساب‌های همان پمپ را نشان بدهد و با پمپ‌های دیگر قاطی
--   نشود — این را خیلی جدی بگیر.»
--
--  ── با کدِ پیوستنِ شش‌رقمی چه فرقی دارد ─────────────────────
--  کدِ پیوستن (`station_join_codes`) موقت است، هش می‌شود و به یک
--  حسابِ گوگل نقش می‌دهد. این یکی **دائمی** است و هیچ حسابی
--  نمی‌خواهد: گوشیِ کارمند آن را می‌زند و در جواب نشانیِ سرورِ
--  خانگی و رمزِ فقط‌خواندنیِ همان پمپ را می‌گیرد. همین و تمام.
--
--  ── چرا خام و نه هش ──────────────────────────────────────────
--  صاحبِ پمپ باید هر وقت خواست کدش را در برنامهٔ کامپیوتر ببیند و
--  به کارمندِ تازه بدهد؛ هشِ یک‌طرفه این را نمی‌گذارد. کد از ۳۲
--  حرف و رقم، هشت‌تایی است (۲^۴۰ حالت) و درِ عمومی محدودیتِ نرخ
--  دارد، پس حدس زدنش شدنی نیست. و بدترین حالتِ لو رفتن، دیدنِ
--  دفتر است نه عوض کردنش — رمزِ خواندن فقط‌خواندنی است. با
--  «عوض کردن» در برنامه، کدِ قبلی همان لحظه از کار می‌افتد.
-- ============================================================

ALTER TABLE stations ADD COLUMN IF NOT EXISTS access_code text NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS uq_stations_access_code
  ON stations(access_code) WHERE access_code <> '';
