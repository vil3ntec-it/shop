-- ---------------------------------------------------------------------------
--  میزِ «کدهای شش‌رقمی» برای دفترِ دومِ کدها — `otp_codes`
--
--  ⛔ درسی که دو بار تکرار شد: **دو دفتر یعنی دو حقیقت.**
--
--  کدِ ورودِ برنامه‌ها در `login_requests` می‌نشیند و پنل از ۱.۴۵.۳ آن را
--  نشان می‌دهد. ولی کدِ **ثبت‌نام** (`register`)، کدِ **رمزِ فراموش‌شده**
--  (`reset`) و کدِ ورودِ ساده (`otp/request`) در `otp_codes`اند — جدولی که
--  هیچ مسیرِ مدیریتی نداشت. پس صاحبِ سامانه کد را در ایمیلش می‌دید و در
--  «کدهای شش‌رقمی»ِ پنل «هنوز کسی کد نخواسته» — و هیچ‌جا نمی‌گفت این کد
--  برای کدام حساب، کدام برنامه و کدام ایمیل ساخته شده.
--
--  ⚠️ `code_sealed` همان قاعدهٔ `login_requests` است: کد برای **دو** کار
--  نگه داشته می‌شود — خودِ ارسال، و نشان دادنش به مدیر وقتی ایمیلِ مشتری
--  خراب است. با مصرف یا انقضا پاک می‌شود و هیچ‌وقت در لاگ نمی‌آید.
-- ---------------------------------------------------------------------------

--  کدام برنامه کد را خواسته (`shop` | `pump`)؛ خالی یعنی نصبِ کهنه
ALTER TABLE otp_codes ADD COLUMN IF NOT EXISTS app         text NOT NULL DEFAULT '';
--  AES-256-GCM با کلیدِ مشتق از رازِ OTP — نه خودِ کد، نه هشِ سنجش
ALTER TABLE otp_codes ADD COLUMN IF NOT EXISTS code_sealed text;
--  راهی که واقعاً به کار رفت: `smtp` | `log` | `sms` | …
ALTER TABLE otp_codes ADD COLUMN IF NOT EXISTS via         text NOT NULL DEFAULT '';
--  ⛔ «ساخته شد» با «رفت» یکی نیست؛ این ستون فرقشان را می‌گوید
ALTER TABLE otp_codes ADD COLUMN IF NOT EXISTS sent_at     bigint;

--  میز بر اساسِ زمان مرتب می‌شود و همیشه چند ده ردیفِ آخر را می‌خواهد
CREATE INDEX IF NOT EXISTS idx_otp_at ON otp_codes(created_at DESC);
