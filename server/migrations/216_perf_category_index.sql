CREATE INDEX IF NOT EXISTS ix_sync_rows_shop_product_category
  ON sync_rows (account_id, (data->>'category'), (COALESCE(data->>'name', '')), row_id)
  WHERE app = 'shop' AND account_kind = 'shop' AND table_name = 'products' AND deleted_at IS NULL;
