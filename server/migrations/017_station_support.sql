-- ============================================================
--  پشتیبانیِ صاحبِ پمپ ↔ مدیرِ سامانه
-- ------------------------------------------------------------
--  ⛔ چیزی که نبود:
--
--  دکان‌دار از روزِ اول می‌توانست به مدیر پیام بدهد (`/api/support`).
--  پمپ‌دار نمی‌توانست — و دو دلیل داشت:
--
--    ۱) رشتهٔ پشتیبانی به `user_id` یا `device_uid` بسته بود، و
--       **برنامهٔ کامپیوترِ پمپ اصلاً حساب ندارد** (قاعدهٔ `CLAUDE.md`:
--       با کدِ شش‌رقمی فعال می‌شود و توکنِ دستگاه می‌گیرد). پس هیچ
--       کلیدی برای رشته‌اش نبود.
--    ۲) اگر هم به `device_uid` بسته می‌شد، پمپی که دو کامپیوتر دارد
--       دو گفت‌وگوی جدا می‌ساخت و مدیر نمی‌فهمید هر دو یک پمپ‌اند.
--
--  پس `station_id`: کلیدِ رشتهٔ هر پمپ. گوشیِ صاحب و کامپیوترِ پمپ،
--  هر دو، به **یک** گفت‌وگو می‌نویسند.
--
--  ⚠️ کلیدِ خارجی ندارد و این عمدی است: `support_threads` هم رشتهٔ
--  دکان دارد هم رشتهٔ پمپ، و `station_id`ِ خالی یعنی «این رشته مالِ
--  پمپ نیست». کلیدِ خارجی روی ستونی که اکثرِ ردیف‌هایش خالی است، فقط
--  هزینه است.
-- ============================================================

ALTER TABLE support_threads ADD COLUMN IF NOT EXISTS station_id text NOT NULL DEFAULT '';

--  «رشتهٔ این پمپ» — تنها پرسشی که این ستون برایش اضافه شد
CREATE INDEX IF NOT EXISTS idx_threads_station
  ON support_threads(station_id)
  WHERE station_id <> '';
