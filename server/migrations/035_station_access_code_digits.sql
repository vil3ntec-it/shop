-- ============================================================
--  کدِ پمپ هشت رقم می‌شود — و کدِ حرفیِ پیشین همچنان در را باز می‌کند
--
--  خواستهٔ صریحِ صاحب سامانه (۱۴۰۵/۰۷/۱۴): «برای هر حساب کاربری یک کد
--  هشت‌رقمی درست بشه تا به برنامهٔ گوشیِ اندروید و آیفون وصل شد و برنامه
--  رو دید، و برای برنامه‌ها هم یک بار زده بشه کافی است.»
--
--  ⛔ کدِ حرفیِ پیشین (‎K7PM-3XQ2‎) **پاک نمی‌شود**، به این ستون می‌رود و
--  هنوز پذیرفته است — گوشی‌ای که با آن وصل شده و هر بار که باز می‌شود
--  همان را دوباره می‌فرستد، نباید با این به‌روزرسانی بیرون بیفتد.
--  تنها «عوض کردنِ کد» به دستِ صاحبِ پمپ هر دو را باطل می‌کند.
--
--  ⚠️ ساختنِ کدهای هشت‌رقمی کارِ `lib/station-access.js` ⇒ `sweep()` است
--  (سرِ بالا آمدنِ سرور و هر شش ساعت)، نه SQL: یکتایی با اعدادِ تصادفی
--  در یک دستورِ SQL تضمین‌شدنی نیست.
-- ============================================================
ALTER TABLE stations ADD COLUMN IF NOT EXISTS access_code_old text NOT NULL DEFAULT '';
CREATE UNIQUE INDEX IF NOT EXISTS uq_stations_access_code_old
  ON stations(access_code_old) WHERE access_code_old <> '';
