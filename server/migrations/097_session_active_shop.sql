--  دکانِ فعالِ نشست — بندِ ۲۹.۲ قاعدهٔ ۱ و ۲، بندِ ۲۱.۱.
--
--  کاربرِ چنددکانی تا امروز همیشه «اولین» عضویتش را می‌گرفت
--  (`shops.membershipOf`، LIMIT 1). حالا نشست می‌تواند دکانش را صریحاً
--  داشته باشد: `tokens.shop_id`، که `POST /api/shop/active` پس از
--  سنجیدنِ عضویت می‌نشاند و تازه‌سازی به توکنِ بعدی می‌برد. هر پرسشِ
--  دکان باز هم عضویتِ فعال در همان دکان را در سرور می‌سنجد.
--
--  ⛔ فقط افزودنی و تهی‌پذیر: نشستِ بی‌انتخاب (همهٔ نشست‌های امروز)
--  دقیقاً همان رفتارِ قبلی را دارد.
--
--  برگشت:
--    ALTER TABLE tokens DROP COLUMN shop_id;
--  (ستونِ تهی بی‌اثر است؛ برگرداندنِ کد بی پاک کردنش هم امن است.)
-- ============================================================

ALTER TABLE tokens ADD COLUMN IF NOT EXISTS shop_id text;
