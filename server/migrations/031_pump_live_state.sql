-- ============================================================
--  حالِ زندهٔ هر پمپ — «برنامه به سرور بگوید، سرور به بات»
--
--  گزارشِ صاحب سامانه (۱۴۰۵/۰۷/۱۴، با عکس): «دو سه تا هشدار استن اما
--  سرور و برنامه بی‌توجهی می‌کنن… بات دنبالِ چیزی نمی‌گرده توی سرور یا
--  برنامه.» تا امروز برنامه فقط هشدارِ **تازه** را می‌فرستاد
--  (`/device/events`)، و سرور هیچ تصویری از «همین حالا چه هشدارهایی
--  باز است» نداشت؛ پس «وضعیت»ِ بات فقط تاریخچه بود، و هر بار که برنامه
--  بسته و باز می‌شد همان هشدارها دوباره «تازه» می‌رفتند.
--
--  ⛔ **دفترِ دوم نیست**: هیچ عددی این‌جا حساب نمی‌شود. همان فهرستی است
--  که برنامهٔ کامپیوتر از `StationSnapshot.Alerts` می‌سازد، به‌علاوهٔ
--  موجودیِ دو مخزن و خلاصهٔ حالِ قرض‌داران (برای جست‌وجوی بات). هر بار
--  برنامه همهٔ آن را می‌فرستد و این ردیف **جایگزین** می‌شود.
-- ============================================================
CREATE TABLE IF NOT EXISTS station_live_state (
  station_id  text   PRIMARY KEY REFERENCES stations(id) ON DELETE CASCADE,
  --  [{k, kind, t, n, f, s, since}] — هشدارهای باز، و از کِی باز شده‌اند
  alerts      jsonb  NOT NULL DEFAULT '[]'::jsonb,
  --  {petrol:{show, threshold, low, near}, diesel:{…}}
  tank        jsonb  NOT NULL DEFAULT '{}'::jsonb,
  --  [{n, sp, sd, sm, p, d, m}] — فقط اگر برنامه فرستاده باشد
  debtors     jsonb,
  debtors_at  bigint,
  --  آخرین باری که برنامهٔ کامپیوتر خبر داد — «برنامه روشن است؟»
  updated_at  bigint NOT NULL
);

--  آخرین پیامِ منوی هر گفت‌وگو — تا منوی تازه دکمه‌های منوی قبلی را
--  بردارد و گفت‌وگو پر از دکمه نشود.
ALTER TABLE telegram_chats ADD COLUMN IF NOT EXISTS menu_msg_id bigint;
