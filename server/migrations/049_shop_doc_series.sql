--  F0-03 — «سری سند» هر دستگاه (A1، B1، …)
--
--  شمارهٔ فاکتور میان گوشی و کامپیوترِ یک دکان تکراری می‌شد: در Sync v1
--  `nextInvoiceNo` هماهنگ نمی‌شود (و نباید بشود — عددِ هر دستگاه مالِ
--  خودش است) و برنامه از ۱ می‌شمارد. حالا هر دستگاه هنگامِ پیوستن یک
--  سریِ کوتاه می‌گیرد و شمارهٔ نمایشی `{سری}-{شماره}` می‌شود.
--
--  ⚠️ ردیف هرگز پاک نمی‌شود: سری‌ای که یک بار داده شد روی فاکتورهای
--  همان دستگاه نشسته و نباید به دستگاهِ دیگری برسد.
--  شمارهٔ فاکتور این‌جا نیست؛ سرور هرگز شماره را عوض نمی‌کند (۳.۵).
-- ============================================================
CREATE TABLE IF NOT EXISTS shop_doc_series (
  shop_id     text   NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
  device_id   text   NOT NULL,
  series      text   NOT NULL,
  user_id     text   NOT NULL DEFAULT '',
  created_at  bigint NOT NULL,
  PRIMARY KEY (shop_id, device_id),
  UNIQUE (shop_id, series)
);
