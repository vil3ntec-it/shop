--  خودشان باشند و بمانند.»
--
--  همان قاعدهٔ `support_media` (۰۳۷): رسانه همان لحظه که **گیرنده**
--  (طرفِ مقابلِ فرستنده) کاملش را گرفت پاک می‌شود. `uploader` برای همین
--  است: 'c' مشتری (صفحهٔ کیو‌آر)، 'o' صاحبِ پمپ (برنامهٔ کامپیوتر).
--  ردیفِ کهنه‌ای که `uploader` ندارد مثلِ پیش تا پایانِ پنجرهٔ نگه‌داری
--  می‌ماند و `chat-relay.sweep()` می‌بردش.
-- ============================================================

ALTER TABLE station_chat_media ADD COLUMN IF NOT EXISTS uploader text;
