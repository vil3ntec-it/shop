-- ============================================================
--  آغازِ دورهٔ آزمایشیِ هر پمپ روی خودِ سرور — و بررسیِ همهٔ حساب‌های پیشین
--
--  خواستهٔ صریحِ صاحب سامانه (۱۴۰۵/۰۷/۱۳): «حساب‌های قدیمی و کسانی که از
--  قبل حساب ساخته بودند هم آزمایشی بگیرند؛ همهٔ حساب‌ها اول چک شوند؛ هر
--  حسابی که آزمایشی نگرفته باید بگیرد — و این آزمایشی از سرور و خودکار
--  داده شود، نه از جای دیگر که سوءاستفاده می‌شود.»
--
--  تا امروز دوره از `stations.created_at` شمرده می‌شد، پس پمپی که مدت‌ها
--  پیش ساخته شده بود ولی برنامه‌اش هرگز به آن وصل نشده بود (نسخه‌های
--  پیشینِ برنامه، یا وصل شدنِ ناموفق) دوره‌اش را **بی آن‌که دیده باشد**
--  از دست داده بود.
--
--  ⛔ **یک بار، همین‌جا، برای همه**: پمپی که
--     ۱) دوره‌اش تمام شده (created_at + روزهای آزمایشی < اکنون)، و
--     ۲) **هیچ** اشتراکی نداشته (نه فعال، نه تعلیق، نه لغو، نه منقضی —
--        درخواستِ `pending` شمرده نمی‌شود؛ همان قاعدهٔ `entitlement.js`)
--  از **همین لحظه** دورهٔ کاملِ تازه می‌گیرد. بقیه همان `created_at`ِ خودشان
--  را نگه می‌دارند — هیچ دورهٔ جاری‌ای دراز یا کوتاه نمی‌شود.
--
--  ⛔ این سطر فقط **یک بار** می‌دود (دفترِ مهاجرت). پس از این، هر پمپِ تازه
--  همان لحظهٔ ساخته شدنش مُهر می‌خورد (`stations.js`) و دوره هیچ‌وقت خودبه‌خود
--  دوباره باز نمی‌شود — وگرنه هر پمپی که دوره‌اش تمام شده با هر راه‌اندازیِ
--  سرور دوباره آزمایشی می‌گرفت.
--
--  ⚠️ و هیچ‌کدام از برنامه نمی‌آید: تاریخِ آغاز فقط همین ستونِ سرور است.
-- ============================================================

ALTER TABLE stations ADD COLUMN IF NOT EXISTS trial_started_at bigint;

UPDATE stations s
   SET trial_started_at = CASE
     WHEN s.created_at + COALESCE(
            (SELECT NULLIF(value, '')::bigint FROM app_config WHERE key = 'pump_trial_days'), 30
          ) * 86400000 < (EXTRACT(EPOCH FROM now()) * 1000)::bigint
      AND NOT EXISTS (
            SELECT 1 FROM station_subscriptions x
             WHERE x.station_id = s.id AND x.status <> 'pending')
     THEN (EXTRACT(EPOCH FROM now()) * 1000)::bigint
     ELSE s.created_at
   END
 WHERE s.trial_started_at IS NULL;
